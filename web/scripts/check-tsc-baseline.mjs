#!/usr/bin/env node
/**
 * `tsc` error ratchet — fails when any single file gains type errors.
 *
 * This is a RATCHET, not a cleanup. It does not require the repo to be
 * type-clean; it requires it to stop getting worse. The repo carries a large
 * pre-existing error backlog (see `tsc-baseline.json`), so the only honest
 * signal is per-file: a shrinking total can hide new debt added elsewhere.
 *
 * Usage:
 *   node scripts/check-tsc-baseline.mjs            # check (exit 1 on regression)
 *   node scripts/check-tsc-baseline.mjs --update   # rewrite the baseline to current
 *
 * `--update` exists so the baseline is regenerated by the tool rather than
 * hand-edited, which keeps it honest when a large pre-existing batch is fixed.
 */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { parseTscErrors, compareTscErrors, formatRegressions } from "./lib/tscBaseline.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const baselinePath = join(here, "tsc-baseline.json");
const update = process.argv.includes("--update");

const tsc = spawnSync("pnpm", ["exec", "tsc", "--noEmit", "-p", "tsconfig.json"], {
  cwd: webRoot,
  encoding: "utf8",
  shell: process.platform === "win32",
});

const output = `${tsc.stdout ?? ""}${tsc.stderr ?? ""}`;
const current = parseTscErrors(output);

// `tsc` exits non-zero purely because errors exist, so its status carries no
// information here. What matters is whether we managed to parse a sane result:
// an empty parse with a non-empty output almost always means the output format
// changed (a new tsc release, a wrapper script) and we would otherwise record a
// silent all-clear.
if (!existsSync(join(webRoot, "tsconfig.json"))) {
  console.error(`ratchet: cannot find tsconfig.json under ${webRoot}`);
  process.exit(1);
}
if (Object.keys(current).length === 0 && /error TS/.test(output)) {
  console.error("ratchet: tsc reported errors but none matched the expected line format.");
  console.error("ratchet: the parser is stale — refusing to record a false all-clear.");
  process.error(output.split(/\r?\n/).slice(0, 20).join("\n"));
  process.exit(1);
}

if (update) {
  writeFileSync(baselinePath, `${JSON.stringify(current, null, 2)}\n`);
  const files = Object.keys(current).length;
  const total = Object.values(current).reduce((a, b) => a + b, 0);
  console.log(`ratchet: baseline rewritten — ${total} error(s) across ${files} file(s).`);
  process.exit(0);
}

if (!existsSync(baselinePath)) {
  console.error(`ratchet: no baseline at ${baselinePath}.`);
  console.error("ratchet: create it with `node scripts/check-tsc-baseline.mjs --update`.");
  process.exit(1);
}

const baseline = JSON.parse(readFileSync(baselinePath, "utf8"));
const { regressions, improvements, before, after } = compareTscErrors(baseline, current);

if (regressions.length === 0) {
  const note = improvements.length ? ` (${improvements.length} file(s) improved; run --update to tighten)` : "";
  console.log(`ratchet: ok — ${after} error(s) across ${Object.keys(current).length} file(s), no file regressed${note}`);
  process.exit(0);
}

console.error(`ratchet: FAILED — ${regressions.length} file(s) gained type errors (total ${before} -> ${after}).`);
console.error(formatRegressions(regressions));
console.error("");
console.error("Fix them, or --update the baseline if the growth is intentional and reviewed.");
process.exit(1);
